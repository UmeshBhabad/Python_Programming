###########################################################################

def Add(No1, No2):
    return No1 + No2

###########################################################################
#
# Function Name :   Sub
# Description   :   used to substract two numbers.
# Input         :   int, int
# Output        :   int
# Author        :   Umesh Shivaji Bhabad
# Date          :   24/01/2026
#
###########################################################################

def Sub(No1, No2):
    return No1 - No2

###########################################################################
#
# Function Name :   Mult
# Description   :   used to multiply two numbers.
# Input         :   int, int
# Output        :   int
# Author        :   Umesh Shivaji Bhabad
# Date          :   24/01/2026
#
###########################################################################

def Mult(No1, No2):
    return No1 * No2

###########################################################################
#
# Function Name :   Div
# Description   :   used to divide two numbers.
# Input         :   int, int
# Output        :   int
# Author        :   Umesh Shivaji Bhabad
# Date          :   24/01/2026
#
###########################################################################

def Div(No1, No2):
    return No1 / No2